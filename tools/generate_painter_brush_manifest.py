#!/usr/bin/env python3
"""Generate the explicit Meson install list from the immutable Painter asset lock.

No brush or preview is rewritten. Default mode checks both bytes and generated
list; --write replaces only meson.build after the entire asset tree validates.
"""
import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'data/painter-mypaint-brushes'
LOCK = ROOT / 'migration/fixtures/legacy-mypaint/assets.json'
LOCK_SHA256 = '018f3db6888b948c23dc1ca383e2cdb57f0df0e4a8d3b202215d29d4fe88f8e7'


def load_lock(data):
    if hashlib.sha256(data).hexdigest() != LOCK_SHA256:
        raise ValueError('pinned legacy asset lock differs')
    lock = json.loads(data)
    if (lock['source_commit'] != 'afa43fae3e920210146abed514f136fd49f671b5' or
            lock['source_root'] != 'data/mypaint-brushes'):
        raise ValueError('legacy asset provenance differs')
    return lock


def records(lock):
    rows = lock['assets']
    names = [r['path'] for r in rows]
    if len(names) != len(set(names)):
        raise ValueError('duplicate asset')
    for name in names:
        p = PurePosixPath(name)
        if (p.is_absolute() or '..' in p.parts or str(p) != name or
                any(c in name for c in "'\\\n\r") or name == 'meson.build'):
            raise ValueError('unsupported asset path: ' + name)
    return sorted(rows, key=lambda r: r['path'])


def validate(directory, rows):
    actual = set()
    for p in directory.rglob('*'):
        if p.is_symlink():
            raise ValueError('asset symlink: ' + str(p))
        if p.is_file() and p.relative_to(directory).as_posix() != 'meson.build':
            actual.add(p.relative_to(directory).as_posix())
    expected = {r['path'] for r in rows}
    if actual != expected:
        raise ValueError('asset census mismatch: missing=%r extra=%r' %
                         (sorted(expected - actual), sorted(actual - expected)))
    for row in rows:
        data = (directory / row['path']).read_bytes()
        if len(data) != row['bytes'] or hashlib.sha256(data).hexdigest() != row['sha256']:
            raise ValueError('asset bytes differ: ' + row['path'])


def render(rows):
    groups = {}
    for row in sorted(rows, key=lambda r: r['path']):
        p = PurePosixPath(row['path'])
        groups.setdefault(str(p.parent), []).append(row['path'])
    out = ['# Generated by tools/generate_painter_brush_manifest.py; do not edit.',
           '# Includes root orphan preview, original notices and support lists.', '']
    for group, names in sorted(groups.items()):
        out.append('install_data(')
        out.extend("  '%s'," % name for name in names)
        target = 'painter-mypaint-brushes' + (('/' + group) if group != '.' else '')
        out.extend(["  install_dir: gimpdatadir / '%s'," % target, ')', ''])
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    rows = records(load_lock(LOCK.read_bytes()))
    validate(ASSETS, rows)
    output = render(rows)
    path = ASSETS / 'meson.build'
    if args.write:
        path.write_text(output)
    elif not path.exists() or path.read_text() != output:
        parser.error('generated Meson asset list differs')
    print('PASS: %d exact assets; sorted explicit Meson install list' % len(rows))


if __name__ == '__main__':
    main()
